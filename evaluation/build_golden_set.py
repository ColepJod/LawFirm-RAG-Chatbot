def _load_sections(chunks_path: Path) -> dict[str, set[str]]:
    sections: dict[str, set[str]] = {}
    for line in chunks_path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        record = json.loads(line)
        metadata = record.get("metadata") or {}
        source_file = str(metadata.get("source_file") or "")
        heading = str(metadata.get("section_heading") or "")
        if source_file and heading:
            sections.setdefault(source_file, set()).add(heading)
    return sections


def _resolve(source_file: str, prefix: str, sections: dict[str, set[str]]) -> str:
    headings = sections.get(source_file, set())
    matches = sorted(
        heading for heading in headings if heading == prefix or heading.startswith(f"{prefix} ")
    )
    if not matches:
        raise ValueError(f"No section like {prefix!r} in {source_file}")
    if len(matches) > 1:
        raise ValueError(f"Ambiguous section prefix {prefix!r}: {matches}")
    return matches[0]


def build_golden_set(chunks_path: Path) -> list[dict[str, object]]:
    sections = _load_sections(chunks_path)
    records: list[dict[str, object]] = []
    for seed in SEEDS:
        keys = [
            section_key(seed.source_file, _resolve(seed.source_file, prefix, sections))
            for prefix in seed.sections
        ]
        records.append(
            {
                "question": seed.question,
                "expected_answer": seed.expected_answer,
                "relevant_section_keys": keys,
                "category": seed.category,
                **({"metadata": seed.metadata} if seed.metadata else {}),
            }
        )
    return records


def main(argv: list[str] | None = None) -> int:
    settings = get_settings()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--chunks",
        type=Path,
        default=settings.index_dir / "chunks.jsonl",
        help="Indexed chunk store to read section headings from.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=settings.golden_set_path,
        help="Destination JSONL file.",
    )
    args = parser.parse_args(argv)

    try:
        records = build_golden_set(args.chunks)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"Could not build golden set: {exc}", file=sys.stderr)
        return 1

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        "\n".join(json.dumps(record, ensure_ascii=False) for record in records) + "\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(records)} golden items to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
